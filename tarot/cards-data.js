/* ---------- 为小阿尔卡纳补齐名称、元素与搜索别名 ---------- */
(function () {
  const suits = window.TAROT_SUITS, ranks = window.TAROT_RANKS;
  for (const c of window.TAROT_CARDS) {
    if (c.id[0] === 'm') { c.arcana = 'major'; continue; }
    const s = suits[c.id[0]], rk = c.id.slice(1), r = ranks[rk];
    c.arcana = 'minor'; c.suit = c.id[0]; c.rank = rk;
    const isCourt = +rk > 10;
    c.zh = s.zh + r.zh;
    c.en = r.en + ' of ' + s.en;
    c.num = isCourt ? r.zh : String(+rk);
    c.el = s.el;
    // 别名：星币3 / 星币三 / 钱币三 / 3 of pentacles / pentacles 3 ...
    const sAliases = s.alias.split(' ');
    const rAliases = r.alias.split(' ').concat(isCourt ? [r.zh] : [r.zh, String(+rk)]);
    const list = [];
    for (const sa of sAliases) for (const ra of rAliases) { list.push(sa + ra); list.push(ra + ' of ' + sa); }
    c.alias = list.join(' ');
  }
})();
